#!/usr/bin/env python3
"""Builds app/fonts/* and app/js/core/fonts-data.js from @fontsource npm packages.

Usage: python3 tools/build-fonts.py <dir-with-extracted-fontsource-packages>
Each package is expected at <dir>/<pkg>/package/files/<pkg>-latin-<w>-<style>.woff2
Only OFL fonts available on npm are bundled; Roblox-only fonts (Builder, Zekton...)
fall back to a similar bundled font in the editor preview (see `approx`).
"""
import json, os, re, shutil, sys
from fontTools.ttLib import TTFont

SRC = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'app', 'fonts')

# Official Roblox font families (Datatype.Font docs, creator-docs). id = json file stem.
